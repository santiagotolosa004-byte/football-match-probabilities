def test_season_code():
    assert season_code(2024) == "2425" and season_code(2099) == "9900"


def test_normalize_github_mirror_format():
    df = read_csv_text(MIRROR_CSV, 2023)
    assert df.loc[0, "date"] == pd.Timestamp("2023-08-11")
    assert df.loc[1, ["home_sot", "away_sot", "home_corners"]].tolist() == [7, 2, 8]
    assert not any(c.startswith("odds_") for c in df.columns)


def test_normalize_football_data_format_with_odds_and_unplayed_fixture():
    df = read_csv_text(FOOTBALL_DATA_CSV, 2024)
    assert len(df) == 2  # the unplayed fixture (no score) is dropped
    assert df["date"].tolist() == [pd.Timestamp("2024-08-16"), pd.Timestamp("2024-08-17")]
    assert df.loc[0, "odds_home"] == 1.62  # market average preferred over Bet365
    assert df.loc[1, "odds_over25"] == 1.6


def test_resolve_team_names():
    teams = ["Man City", "Man United", "Nott'm Forest", "Arsenal"]
    assert resolve_team("arsenal", teams) == "Arsenal"
    assert resolve_team("Forest", teams) == "Nott'm Forest"
    assert resolve_team("Man Utd", teams) == "Man United"
    with pytest.raises(ValueError):
        resolve_team("Real Madrid", teams)


